    #[test]
    fn ledger_monotonic_accumulate() {
        let mut l = LedgerStatement::new(0);
        l.accumulate(15_252_000, 1).unwrap();
        l.accumulate(8_928_000_000_000, 86_400_000_000_000_000_000_000).unwrap();
        assert_eq!(l.total_saved_uj, 15_252_000 + 8_928_000_000_000);
        assert_eq!(l.balance_uj(), l.total_saved_uj);
    }

    #[test]
    fn ledger_rejects_non_monotonic_atto() {
        let mut l = LedgerStatement::new(0);
        l.accumulate(100, 10).unwrap();
        assert!(l.accumulate(100, 5).is_err());
    }

    #[test]
    fn credit_cannot_exceed_saved() {
        let mut l = LedgerStatement::new(0);
        l.accumulate(100, 1).unwrap();
        assert!(l.credit(50, 2).is_ok());
        assert_eq!(l.balance_uj(), 50);
        assert!(l.credit(100, 3).is_err());
        assert_eq!(l.balance_uj(), 50);
    }

    #[test]
    fn balance_arc_and_xrp_exact_integer() {
        let mut l = LedgerStatement::new(0);
        // 8.928 kWh = 8.928 × 3.6e12 µJ = 32_140_800_000_000 µJ
        l.accumulate(32_140_800_000_000u64, 1).unwrap();
        assert_eq!(l.balance_micro_arc(), 8_928_000); // = 8.928 ARC

        let pricing = Pricing::reference(); // $0.10/kWh, $2.20/XRP
        // drops = 32_140_800_000_000 × 100_000 / (3_600_000 × 2_200_000)
        //       = 3_214_080_000_000_000_000 / 7_920_000_000_000
        //       = 405_818
        assert_eq!(l.balance_drops(&pricing), 405_818);
    }

    #[test]
    fn chain_tag_changes_on_every_entry() {
        let mut l = LedgerStatement::new(0);
        let t0 = trits_to_rep_c_string(&l.chain_tag);
        l.accumulate(100, 1).unwrap();
        let t1 = trits_to_rep_c_string(&l.chain_tag);
        l.accumulate(100, 2).unwrap();
        let t2 = trits_to_rep_c_string(&l.chain_tag);
        assert_ne!(t0, t1);
        assert_ne!(t1, t2);
    }

    #[test]
    fn enhanced_md_contains_canonical_sections() {
        let mut l = LedgerStatement::new(0);
        l.accumulate(32_140_800_000_000u64, 1).unwrap();
        let md = l.render_enhanced_md("tdns:hmodal-demo:01", &Pricing::reference());
        assert!(md.starts_with("---"));
        assert!(md.contains("doc_kind: eac-statement-of-account"));
        assert!(md.contains("# Energy Attestation Certificate"));
        assert!(md.contains("## Ledger Totals"));
        assert!(md.contains("## XRP Equivalent"));
        assert!(md.contains("## Chain Tag"));
        assert!(md.contains("8.928000")); // ARC balance
        assert!(md.contains("0.405818")); // XRP balance
        assert!(md.contains("```trit-rep-c"));
        assert!(md.contains("```math"));
    }

    #[test]
    fn cipher_roundtrips_pure_ternary() {
        let pt = rep_c_string_to_trits(
            "1231231232132133221231231232132132133211231231232132132133",
        )
        .unwrap();
        let key = rep_c_string_to_trits("21311232313").unwrap();
        let ct = encrypt_trits(&pt, &key);
        let recovered = decrypt_trits(&ct, &key);
        assert!(pt.equal_values(&recovered));
        // Ciphertext must not equal plaintext (vanishingly unlikely otherwise).
        assert!(!pt.equal_values(&ct));
    }

    #[test]
    fn cipher_wrong_key_yields_different_plaintext() {
        let pt = rep_c_string_to_trits("12312312321321332").unwrap();
        let key_a = rep_c_string_to_trits("213").unwrap();
        let key_b = rep_c_string_to_trits("312").unwrap();
        let ct = encrypt_trits(&pt, &key_a);
        let bad = decrypt_trits(&ct, &key_b);
        assert!(!pt.equal_values(&bad));
    }
