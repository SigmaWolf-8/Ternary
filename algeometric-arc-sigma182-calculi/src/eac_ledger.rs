/// Render a `TritVec` as a Rep-C base-3 string over the alphabet `{1,2,3}`.
pub fn trits_to_rep_c_string(v: &TritVec) -> String {
    let slice = v.as_slice();
    let mut s = String::with_capacity(slice.len());
    for t in slice {
        let c = match t {
            Trit::One => '1',
            Trit::Two => '2',
            Trit::Three => '3',
        };
        s.push(c);
    }
    s
}

/// Parse a Rep-C base-3 string (alphabet `{1,2,3}`) into a `TritVec`.
/// Returns `None` if any character is outside the alphabet.
pub fn rep_c_string_to_trits(s: &str) -> Option<TritVec> {
    let mut out = Vec::with_capacity(s.len());
    for c in s.chars() {
        let t = match c {
            '1' => Trit::One,
            '2' => Trit::Two,
            '3' => Trit::Three,
            _ => return None,
        };
        out.push(t);
    }
    Some(TritVec::from_trits(&out))
}

