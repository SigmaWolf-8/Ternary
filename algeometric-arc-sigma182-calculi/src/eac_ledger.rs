#[cfg(feature = "bridge")]
pub mod bridged {
    //! Byte-boundary helpers gated behind `feature = "bridge"`.
    //!
    //! These are the **only** functions in `eac_ledger` that touch
    //! opaque bytes; the pure ternary path stays no_std + alloc clean.

    use super::{decrypt_trits, encrypt_trits};
    use crate::bridge::{from_bytes_packed, to_bytes_packed};
    use crate::tritvec::TritVec;
    use alloc::string::String;
    use alloc::vec::Vec;

    /// Encrypt a Markdown statement of account (UTF-8 string) under a
    /// trit key, returning packed-base-3 ciphertext bytes.
    pub fn encrypt_md_to_packed(md: &str, key: &TritVec) -> Vec<u8> {
        // Convert MD bytes → TritVec via the canonical packed-base-3 codec.
        let pt = match from_bytes_packed(md.as_bytes()) {
            Some(v) => v,
            None => return Vec::new(),
        };
        let ct = encrypt_trits(&pt, key);
        to_bytes_packed(&ct)
    }

    /// Inverse of [`encrypt_md_to_packed`].  Returns `None` if the
    /// recovered byte string is not valid UTF-8 (e.g. wrong key).
    pub fn decrypt_packed_to_md(ct_bytes: &[u8], key: &TritVec) -> Option<String> {
        let ct = from_bytes_packed(ct_bytes)?;
        let pt = decrypt_trits(&ct, key);
        let bytes = to_bytes_packed(&pt);
        String::from_utf8(bytes).ok()
    }
}

