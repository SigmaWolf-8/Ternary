// Pure-ternary GF(3) stream cipher
// ════════════════════════════════════════════════════════════════════════

/// Encrypt a plaintext `TritVec` with a `TritVec` key under a pure
/// GF(3) stream cipher.  See module docs for the keystream construction.
pub fn encrypt_trits(pt: &TritVec, key: &TritVec) -> TritVec {
    let n = pt.len();
    if n == 0 || key.is_empty() {
        return pt.clone();
    }
    let ks = expand_keystream(key, n);
    let pt_slice = pt.as_slice();
    let ks_slice = ks.as_slice();
    let mut out = Vec::with_capacity(n);
    for i in 0..n {
        let pv = pt_slice[i].value_b();
        let kv = ks_slice[i].value_b();
        out.push(Trit::from_b((pv + kv) % 3).unwrap_or(Trit::One));
    }
    TritVec::from_trits(&out)
}

/// Decrypt a ciphertext `TritVec` with a `TritVec` key.  Inverse of
/// [`encrypt_trits`].
pub fn decrypt_trits(ct: &TritVec, key: &TritVec) -> TritVec {
    let n = ct.len();
    if n == 0 || key.is_empty() {
        return ct.clone();
    }
    let ks = expand_keystream(key, n);
    let ct_slice = ct.as_slice();
    let ks_slice = ks.as_slice();
    let mut out = Vec::with_capacity(n);
    for i in 0..n {
        let cv = ct_slice[i].value_b();
        let kv = ks_slice[i].value_b();
        out.push(Trit::from_b((3 + cv - kv) % 3).unwrap_or(Trit::One));
    }
    TritVec::from_trits(&out)
}

/// Expand a key TritVec to a `want`-trit keystream using a 27-trit
/// state and the (7, 11, 13) coprime-triple lagged GF(3) recurrence:
///
/// ```text
///   state[i] = (state[i-7] + state[i-11] + state[i-13]) mod 3   (i ≥ 27)
/// ```
///
/// The first 27 trits of the state are seeded by cycling the key
/// through three coprime-indexed taps so short keys still distribute
/// across the full state.
fn expand_keystream(key: &TritVec, want: usize) -> TritVec {
    let key_len = key.len();
    let key_slice = key.as_slice();
    let state_len = 27usize;
    let total = if want < state_len { state_len } else { want };
    let mut state: Vec<Trit> = Vec::with_capacity(total);

    // Seed first 27 trits.
    for i in 0..state_len {
        let k = key_slice[i % key_len].value_b();
        let mix_a = key_slice[(i.wrapping_mul(7)) % key_len].value_b();
        let mix_b = key_slice[(i.wrapping_mul(11)) % key_len].value_b();
        state.push(Trit::from_b((k + mix_a + mix_b) % 3).unwrap_or(Trit::One));
    }

    // Lagged recurrence.
    for i in state_len..want {
        let a = state[i - 7].value_b();
        let b = state[i - 11].value_b();
        let c = state[i - 13].value_b();
        state.push(Trit::from_b((a + b + c) % 3).unwrap_or(Trit::One));
    }

    state.truncate(want);
    TritVec::from_trits(&state)
}

